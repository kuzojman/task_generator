"""Генераторы задач ЕГЭ № 14 «Системы счисления» (класс «Подсчёт (цифры)»).

Каждая `task_<ID>()` возвращает `{"condition": str, "answer": int}` — то же
задание, что в исходнике, но с другими числами и посчитанным ответом.

Как устроен прототип:

* строка условия с метками `{=выражение}` (считается из `params`),
  `{имя}` (подставляет уже выбранное значение) и `{{имя}}` (то же значение,
  но в фигурных скобках) — последнее нужно там, где число стоит в показателе
  LaTeX-степени: `^{{p1}}` -> `^{30}`; без скобок LaTeX поднял бы только первую
  цифру, поэтому показатели пишутся всегда со скобками, даже однозначные;
* `params` — словарь меток: `'20-40'` (диапазон) или `'2|3|5'` (список).
  Оригинальные числа задачи входят в диапазоны, поэтому подстановка
  оригинальных значений даёт исходное задание;
* `check` — строка-условие на выбранные значения (проверяется в `while True`).

Основания в выражении и основание записи ответа — степени одного корня `r`:
выбираются `r` и показатели `e1, e2, m`, а сами основания получаются как
`r**e1`, `r**e2`, `r**m`. Всё, что зависит от основания (целевая цифра
`r**m-1`, хвост-константа), тоже выражено через модель.
"""

import random
import re


#: Предел размера значения: 40 000 бит (~12 000 десятичных цифр).
MAX_BITS = 40000


def pick(spec):
    """Случайное значение метки: 'a-b' — из диапазона, 'a|b|c' — из списка."""
    if '|' in spec:
        return int(random.choice(spec.split('|')))
    if '-' not in spec:
        return int(spec)
    low, high = spec.split('-')
    return random.randint(int(low), int(high))


def fill(proto, params):
    """Подставляет значения в прототип: (текст условия, значения).

    `{=выражение}` -> значение выражения, `{имя}` -> значение метки,
    `{{имя}}` -> значение метки в фигурных скобках. Последнее нужно для
    показателей LaTeX-степени: `^{{p1}}` -> `^{30}`, иначе степень подняла бы
    только первую цифру числа.
    """
    values = {name: pick(spec) for name, spec in params.items()}

    def computed(match):
        return str(eval(match.group(1), {}, values))

    def named(match):
        name = match.group(1)
        return str(values[name]) if name in values else match.group(0)

    def braced(match):
        name = match.group(1)
        if name not in values:
            return match.group(0)
        return '{' + str(values[name]) + '}'

    text = re.sub(r'\{=([^{}]+)\}', computed, proto)
    text = re.sub(r'\{\{(\w+)\}\}', braced, text)
    return re.sub(r'\{(\w+)\}', named, text), values


def expr_of(text):
    """Выражение из \\( ... \\) -> выражение на Python (для eval)."""
    match = re.search(r'\\\((.+?)\\\)', text, re.S)
    body = match.group(1) if match else text
    while '\\frac' in body:
        start = body.index('\\frac')
        numerator, stop = group_of(body, start + len('\\frac'))
        denominator, stop = group_of(body, stop)
        glue = '((' + numerator + ')//(' + denominator + '))'
        body = body[:start] + glue + body[stop:]
    body = re.sub(r'\{([^{}]*)\}', r'\1', body)
    body = body.replace('\\cdot', '*').replace('\\times', '*')
    return body.replace('^', '**').replace(' ', '')


def group_of(text, position):
    """Содержимое LaTeX-группы {...} и позиция сразу после неё."""
    depth = 0
    for index in range(position, len(text)):
        if text[index] == '{':
            depth += 1
        elif text[index] == '}':
            depth -= 1
            if depth == 0:
                return text[position + 1:index], index + 1
    raise ValueError('не закрыта фигурная скобка: ' + text)


def to_digits(value, base):
    """Цифры числа в системе с основанием base, младшая цифра первая."""
    result = []
    while value:
        value, remainder = divmod(value, base)
        result.append(remainder)
    return result or [0]


def count_digits(proto, params, base, digit, check=None):
    """Задание «сколько раз цифра встречается в записи значения».

    base и digit — выражения от `params` (например, 'r**m' и 'r**m-1').
    """
    while True:
        condition, values = fill(proto, params)
        if check is not None and not eval(check, {}, values):
            continue
        value = eval(expr_of(condition), {}, {})
        if value <= 0 or value.bit_length() > MAX_BITS:
            continue
        base_value = eval(base, {}, values)
        digit_value = eval(digit, {}, values)
        return {
            "condition": condition,
            "answer": to_digits(value, base_value).count(digit_value),
        }


def count_digits_giant(proto, params, answer, check):
    """Задание «сколько раз цифра встречается в записи» без счёта значения.

    Значение такого выражения не вычисляется: у 5 * 3**98765432101 около
    1.6e11 бит, то есть в 4e6 раз больше MAX_BITS, а запись занимает
    ~10**11 цифр. Поэтому ответ берётся по формуле `answer` -- выражению от
    `params` (например, 'c - 2'), выведенной по схеме цифр значения.
    Формула верна только при выполненном `check`, и её нужно проверять на
    малых аналогах (честный eval выражения + to_digits), поэтому check
    обязателен.
    """
    if check is None:
        raise ValueError('count_digits_giant: формула ответа верна только '
                         'при выполненном check')
    while True:
        condition, values = fill(proto, params)
        if not eval(check, {}, values):
            continue
        result = eval(answer, {}, values)
        if not isinstance(result, int) or result <= 0:
            continue
        return {"condition": condition, "answer": result}


