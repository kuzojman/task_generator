# --- Форма 10: деление на r^2-1 (4125) -------------------------------------

# В выражении есть деление на постоянную r**2-1 (при r = 3 это 8), и оно
# всегда нацело: 81**b - 1 = 3**(4*b) - 1, а 9 = 3**2 = 1 (mod 8), поэтому
# 3**(4*b) = 1 (mod 8) и 8 | 81**b - 1 при любом b. Второй множитель,
# (8 + 1)**m + 1, на 8 не делится и не должен: восьмёрка уходит в первый.
#
# 4125: (r**4)**a - ((r**4)**b - 1)*((r**2 - 1 + 1)**m + 1)/(r**2 - 1)
#       - (r**2 - 1), основание r; ответ -- количество единиц.
#   T = (r**(4*b) - 1)/(r**2 - 1) = 1 + r**2 + ... + r**(4*b-2) -- шаблон
#   1010...101: 4*b - 1 разрядов и 2*b единиц на чётных местах (деление на
#   r**2 - 1 -- то же, что деление на 11 в десятичной записи);
#   Q = T*((r**2)**m + 1) = T + T*r**(2*m) -- шаблон плюс его копия со
#   сдвигом на 2*m разрядов. Переноса нет нигде: складываются только
#   0 + 0 и 1 + 1 = 2 < r, поэтому сумма 1 + 1 = 2 просто занимает разряд;
#   N = r**(4*a) - Q - (r**2 - 1).
#   r**(4*a) - 1 -- прогон из 4*a цифр r-1, а цифры Q + r**2 - 2 не больше
#   r-1, значит вычитание идёт без заёмов и лишь дополняет каждую цифру:
#   цифра(N, i) = (r-1) - цифра(Q + r**2 - 2, i). При r = 3 дополнение до 2
#   оставляет 1 единицей, поэтому единицы в N стоят там же, где в Q + 7.
#   Прибавление r**2 - 2 = 7 = 21_3 задевает только два младших разряда
#   (у Q там 1 и 0) и ровно одну единицу -- младшую -- превращает в ноль.
#
# Отсюда две формулы ответа:
#   m <= 2*b - 1: копии перекрываются, единиц в Q ровно 2*m (m ниже полосы
#       наложения, m -- в верхней копии), после +7 остаётся 2*m - 1;
#   m >= 2*b: копии разошлись, единиц в Q 4*b, после +7 -- 4*b - 1.
# Поэтому ответ всегда нечётен (2*m - 1 или 4*b - 1), а показатель a в
# формулы не входит: он задаёт только длину записи (4*a разрядов сверху, все
# цифры r-1) и на число единиц не влияет. Разброс ответа даёт только m.
#
# r закреплён одним значением: при r = 4 дополнение до 3 переводит 1 -> 2,
# 2 -> 1, 0 -> 3, и ответ равен 2*b - m -- другая формула, а при r >= 5
